"""Константы приложения projects."""

# ---------------------------------------------------------------------------
#  Статусы проекта
# ---------------------------------------------------------------------------

PROJECT_STATUS_OPEN = "open"
PROJECT_STATUS_CLOSED = "closed"

PROJECT_STATUS_CHOICES = (
    (PROJECT_STATUS_OPEN, "Открыт"),
    (PROJECT_STATUS_CLOSED, "Закрыт"),
)

# Длина max_length вычисляется по самому длинному ключу,
# чтобы при добавлении нового статуса схему не пришлось править вручную.
PROJECT_STATUS_MAX_LENGTH = max(
    len(value) for value, _label in PROJECT_STATUS_CHOICES
)


# ---------------------------------------------------------------------------
#  Ограничения полей
# ---------------------------------------------------------------------------

PROJECT_NAME_MAX_LENGTH = 200


# ---------------------------------------------------------------------------
#  Пагинация
# ---------------------------------------------------------------------------

PROJECTS_PER_PAGE = 12
